TOKEN_PATTERN = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)


def get_russian_stopwords() -> Set[str]:
    try:
        from nltk.corpus import stopwords
        return set(stopwords.words("russian"))
    except Exception:
        return set(FALLBACK_RUSSIAN_STOPWORDS)


STOPWORDS_SET = get_russian_stopwords()


@lru_cache(maxsize=10000)
def lemmatize_token(token: str) -> str:
    if _MORPH is not None:
        return _MORPH.parse(token)[0].normal_form
    return _CORPUS_LEMMA_MAP.get(token, token)


def tokenize_and_process(
    text: str,
    lemmatize: bool = False,
    remove_stopwords: bool = False,
) -> List[str]:
    """Очищает, токенизирует и нормализует текст по заданным параметрам."""
    if not isinstance(text, str) or not text.strip():
        return []
    tokens = TOKEN_PATTERN.findall(text.lower())
    if lemmatize:
        tokens = [lemmatize_token(t) for t in tokens]
    if remove_stopwords:
        tokens = [t for t in tokens if t not in STOPWORDS_SET]
    return tokens


def preprocess_text(
    text: str,
    lemmatize: bool = False,
    remove_stopwords: bool = False,
) -> str:
    return " ".join(tokenize_and_process(text, lemmatize=lemmatize, remove_stopwords=remove_stopwords))


def build_document_corpus_series(documents_df) -> List[str]:
    combined = (
        documents_df["title"].fillna("")
        + " "
        + documents_df["section"].fillna("")
        + " "
        + documents_df["text"].fillna("")
    )
    return combined.tolist()
